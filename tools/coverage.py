"""Generate/check requirement coverage and test source fingerprints (not test results)."""

import argparse
import ast
import hashlib
import json
import re
from pathlib import Path

import check_requirements
from kotlin_source import mask_literals

ROOT = Path(__file__).resolve().parents[1]
REPORT = "docs/coverage.md"
SNAPSHOT = "docs/coverage-snapshot.json"
TEST_ROOTS = ("app/src/test", "app/src/androidTest", "tools/tests")


def test_sources(root):
    return sorted(
        (
            path
            for folder in TEST_ROOTS
            for path in (root / folder).rglob("*")
            if path.is_file() and path.suffix in {".java", ".kt", ".py"}
        ),
        # Path comparison is case-insensitive on Windows and case-sensitive on
        # Linux. Serialized inventory order must use the same rule on both.
        key=lambda path: path.relative_to(root).as_posix(),
    )


def cases(path):
    source = path.read_text(encoding="utf-8")
    if path.suffix == ".py":
        return sorted(
            f"{node.name}.{method.name}"
            for node in ast.parse(source).body
            if isinstance(node, ast.ClassDef)
            for method in node.body
            if isinstance(method, ast.FunctionDef) and method.name.startswith("test_")
        )
    if path.suffix == ".kt":
        code = mask_literals(source)
        junit = re.findall(
            r"@(?:org\.junit\.)?Test\b(?:\s*\([^)]*\))?\s*"
            r"(?:(?:public|internal|protected|private|open|final|override)\s+"
            r"|@[\w.]+(?:\s*\([^()]*\))?\s*)*"
            r"fun\s+(\w+)\s*\(",
            code,
        )
        entries = re.findall(r"\bfun\s+(run|onStart)\s*\(", code)
        return sorted(set(junit + entries))
    # Native suites contain many assertions in run/onStart; list those entry
    # points explicitly rather than misrepresent helpers as independent tests.
    junit = re.findall(r"@Test\s+public\s+void\s+(\w+)\s*\(", source)
    entries = re.findall(r"\b(?:void|String)\s+(run|onStart)\s*\(", source)
    return sorted(set(junit + entries))


def generate(root):
    data = json.loads((root / "docs/requirements.json").read_text(encoding="utf-8"))
    errors = check_requirements.validate(data, root)
    inventory = {}
    for path in test_sources(root):
        # Canonical LF makes fingerprints stable between Windows and Actions.
        content = path.read_text(encoding="utf-8")
        inventory[path.relative_to(root).as_posix()] = {
            "sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
            "cases": cases(path),
        }
    mapped = set()
    lines = [
        "# Requirement coverage",
        "",
        "Generated by `python tools/coverage.py update`; edit `docs/requirements.json`.",
        "Run `python tools/coverage.py check` after every test change.",
        "",
        "Mappings describe intended checks, not execution results. Native run/onStart",
        "entries contain multiple assertions; this report does not count each as a case.",
        "Scenario dimensions are selection obligations, not proof every combination ran.",
        "Current evidence belongs in versioned change/run records under `testresults/`.",
        "Historical device evidence: [index](../testresults/README.md).",
        "",
        "| Requirement | Spec | Coverage | Test entry points |",
        "| --- | --- | --- | --- |",
    ]
    resolved = {}
    for req in data["requirements"]:
        checks = []
        for ref in req.get("checks", []):
            path, separator, selection = ref.partition("::")
            available = inventory.get(path, {}).get("cases", [])
            matching = [
                case for case in available if case == selection or case.startswith(selection + ".")
            ]
            if not separator or not matching:
                errors.append(f"{req['id']}: missing test case {ref}")
            for case in matching:
                checks.append(f"{path}::{case}")
                mapped.add((path, case))
        if req["coverage"] in {"mapped", "partial"} and not checks:
            errors.append(f"{req['id']}: mapped coverage needs concrete checks")
        resolved[req["id"]] = sorted(set(checks))
        links = "<br>".join(
            f"[{ref.split('::')[1]}](../{ref.split('::')[0]})" for ref in sorted(set(checks))
        )
        lines.append(
            f"| {req['id']} | {req['spec_requirement']} | {req['coverage']} | {links or 'Manual/deferred'} |"
        )
    lines += ["", "## Scenarios and gaps", ""]
    for req in data["requirements"]:
        dimensions = "; ".join(
            f"{dim}: {', '.join(data['dimensions'][dim])}" for dim in req["dimensions"]
        )
        lines += [
            f"### {req['id']}",
            "",
            req["criterion"],
            "",
            f"Scenario dimensions: {dimensions}.",
            "",
            f"Gap: {req['gap'] or 'No mapping gap declared; execution still requires run evidence.'}",
            "",
        ]
    for path, entry in inventory.items():
        for case in entry["cases"]:
            if (path, case) not in mapped:
                errors.append(f"Unmapped test entry: {path}::{case}")
    if errors:
        raise ValueError("\n".join(errors))
    snapshot = {"schema_version": 1, "test_sources": inventory, "requirements": resolved}
    return "\n".join(lines), json.dumps(snapshot, indent=2) + "\n"


def update(root):
    report, snapshot = generate(root)
    (root / REPORT).write_text(report, encoding="utf-8", newline="\n")
    (root / SNAPSHOT).write_text(snapshot, encoding="utf-8", newline="\n")


def check(root):
    expected = generate(root)
    for path, content in zip((REPORT, SNAPSHOT), expected, strict=True):
        if not (root / path).is_file() or (root / path).read_text(encoding="utf-8") != content:
            raise ValueError(
                f"Stale {path}; reconcile mappings and run python tools/coverage.py update"
            )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["update", "check"])
    args = parser.parse_args()
    try:
        (update if args.action == "update" else check)(ROOT)
    except (ValueError, OSError, KeyError, SyntaxError) as error:
        print(f"FAIL {error}")
        return 1
    print(f"PASS requirement coverage {args.action} (mapping only)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
